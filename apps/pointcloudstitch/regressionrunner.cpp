bool writeAsciiPly(const QString &path, const QVector<pointcloud::Point3D> &points,
                   QString *error)
{
    QSaveFile file(path);
    if (!file.open(QIODevice::WriteOnly)) {
        if (error) *error = QStringLiteral("无法创建输出文件：%1").arg(path);
        return false;
    }
    QTextStream stream(&file);
    stream.setLocale(QLocale::c());
    stream.setRealNumberNotation(QTextStream::ScientificNotation);
    stream.setRealNumberPrecision(9);
    stream << "ply\nformat ascii 1.0\n"
              "comment generated by pointcloudstitch transform-only regression\n"
           << "element vertex " << points.size() << "\n"
              "property float x\nproperty float y\nproperty float z\n"
              "end_header\n";
    for (const pointcloud::Point3D &point : points)
        stream << point.x << ' ' << point.y << ' ' << point.z << '\n';
    stream.flush();
    if (stream.status() != QTextStream::Ok || !file.commit()) {
        if (error) *error = QStringLiteral("写入 PLY 数据失败：%1").arg(path);
        return false;
    }
    return true;
}

QMatrix4x4 poseMatrix(const QVector<double> &pose)
{
    QMatrix4x4 matrix;
    matrix.setToIdentity();
    matrix.rotate(float(pose.value(5)), 0.0f, 0.0f, 1.0f);
    matrix.rotate(float(pose.value(4)), 0.0f, 1.0f, 0.0f);
    matrix.rotate(float(pose.value(3)), 1.0f, 0.0f, 0.0f);
    matrix(0, 3) = float(pose.value(0));
    matrix(1, 3) = float(pose.value(1));
    matrix(2, 3) = float(pose.value(2));
    return matrix;
}

bool readCalibration(const QString &path, QMatrix4x4 *matrix, QString *error)
{
    QFile file(path);
    if (!file.open(QIODevice::ReadOnly | QIODevice::Text)) {
        *error = QStringLiteral("无法打开标定文件：%1").arg(path);
        return false;
    }
    QXmlStreamReader xml(&file);
    bool inside = false;
    QVector<double> rotation, translation;
    while (!xml.atEnd()) {
        xml.readNext();
        if (xml.isEndElement() && xml.name() == QStringLiteral("RTmatDepth2robot")) inside = false;
        if (!xml.isStartElement()) continue;
        if (xml.name() == QStringLiteral("RTmatDepth2robot")) inside = true;
        else if (inside && xml.name() == QStringLiteral("RotMat")) {
            rotation.resize(9);
            for (int row = 0; row < 3; ++row)
                for (int column = 0; column < 3; ++column) {
                    bool ok = false;
                    rotation[row * 3 + column] = xml.attributes()
                        .value(QStringLiteral("r%1%2").arg(row).arg(column)).toDouble(&ok);
                    if (!ok) rotation.clear();
                }
        } else if (inside && xml.name() == QStringLiteral("TVec")) {
            translation.resize(3);
            for (int index = 0; index < 3; ++index) {
                bool ok = false;
                translation[index] = xml.attributes().value(QStringLiteral("t%1").arg(index)).toDouble(&ok);
                if (!ok) translation.clear();
            }
        }
    }
    if (xml.hasError() || rotation.size() != 9 || translation.size() != 3) {
        *error = xml.hasError() ? xml.errorString()
                                : QStringLiteral("XML 中 RTmatDepth2robot/RotMat/TVec 不完整");
        return false;
    }
    matrix->setToIdentity();
    for (int row = 0; row < 3; ++row) {
        for (int column = 0; column < 3; ++column) (*matrix)(row, column) = float(rotation[row * 3 + column]);
        (*matrix)(row, 3) = float(translation[row]);
    }
    return true;
}

bool readPoseInfo(const QString &path, QHash<int, PoseRecord> *records, QString *error)
{
    QFile file(path);
    if (!file.open(QIODevice::ReadOnly | QIODevice::Text)) {
        *error = QStringLiteral("无法打开位姿文件：%1").arg(path);
        return false;
    }
    const QString number = QStringLiteral("([-+]?(?:\\d+(?:\\.\\d*)?|\\.\\d+)(?:[eE][-+]?\\d+)?)");
    const QRegularExpression pattern(
        QStringLiteral("A(\\d+)\\s+Start\\s+X%1\\s+Y%1\\s+Z%1\\s+RX%1\\s+RY%1\\s+RZ%1\\s*;\\s*END\\s+X%1\\s+Y%1\\s+Z%1\\s+RX%1\\s+RY%1\\s+RZ%1")
            .arg(number), QRegularExpression::CaseInsensitiveOption);
    while (!file.atEnd()) {
        const QString line = QString::fromUtf8(file.readLine()).trimmed();
        const auto match = pattern.match(line);
        if (!match.hasMatch()) continue;
        PoseRecord record;
        record.scan = match.captured(1).toInt();
        bool ok = true;
        for (int index = 0; index < 6; ++index) record.start.push_back(match.captured(index + 2).toDouble(&ok));
        for (int index = 0; index < 6; ++index) record.end.push_back(match.captured(index + 8).toDouble(&ok));
        if (!ok) {
            *error = QStringLiteral("位姿行包含无效数字：%1").arg(line);
            return false;
        }
        records->insert(record.scan, record);
    }
    if (records->size() < 2) {
        *error = QStringLiteral("位姿文件中少于两组有效 Start/End");
        return false;
    }
    return true;
}

QVector<float> parseLevels(const QString &text, QString *error)
{
    QVector<float> result;
    const QStringList parts = text.split(QRegularExpression(QStringLiteral("[\\s,，/]+")), Qt::SkipEmptyParts);
    for (const QString &part : parts) {
        bool ok = false;
        const float value = part.toFloat(&ok);
        if (!ok || value <= 0) {
            *error = QStringLiteral("参数层级必须包含三个正数：%1").arg(text);
            return {};
        }
        result.push_back(value);
    }
    if (result.size() != 3) *error = QStringLiteral("参数层级必须恰好包含三个数：%1").arg(text);
    return result;
}

QJsonArray vectorJson(const QVector<double> &values)
{
    QJsonArray result;
    for (double value : values) result.append(value);
    return result;
}

