int runRegression(const QStringList &arguments)
{
    QCommandLineParser parser;
    parser.setApplicationDescription(QStringLiteral("pointcloudstitch 多帧回归诊断"));
    parser.addHelpOption();
    const QCommandLineOption regressionOption(QStringLiteral("regression"), QStringLiteral("运行多帧回归诊断"));
    const QCommandLineOption inputOption(QStringLiteral("input-dir"), QStringLiteral("ASCII PLY 目录"), QStringLiteral("path"));
    const QCommandLineOption poseOption(QStringLiteral("pose-info"), QStringLiteral("Start/End 位姿 TXT"), QStringLiteral("path"));
    const QCommandLineOption calibrationOption(QStringLiteral("calibration"), QStringLiteral("Eye-in-Hand XML"), QStringLiteral("path"));
    const QCommandLineOption reportOption(QStringLiteral("report"), QStringLiteral("输出 JSON 报告"), QStringLiteral("path"));
    const QCommandLineOption outputOption(QStringLiteral("output-dir"), QStringLiteral("转换模式输出 PLY 目录"), QStringLiteral("path"));
    const QCommandLineOption voxelOption(QStringLiteral("voxel-levels"), QStringLiteral("三个体素层级"), QStringLiteral("values"), QStringLiteral("1 0.5 0.2"));
    const QCommandLineOption distanceOption(QStringLiteral("correspondence-distances"), QStringLiteral("三个对应距离"), QStringLiteral("values"), QStringLiteral("3 1.5 0.6"));
    const QCommandLineOption transformOnlyOption(QStringLiteral("transform-only"), QStringLiteral("仅执行手眼坐标转换，跳过预对齐和 ICP"));
    parser.addOptions({regressionOption, inputOption, poseOption, calibrationOption, reportOption, outputOption, voxelOption, distanceOption, transformOnlyOption});
    parser.process(arguments);
    const QString inputDirectory = parser.value(inputOption);
    const QString posePath = parser.value(poseOption);
    const QString calibrationPath = parser.value(calibrationOption);
    const QString reportPath = parser.value(reportOption);
    const QString outputDirectory = parser.value(outputOption);
    if (inputDirectory.isEmpty() || posePath.isEmpty() || calibrationPath.isEmpty() || reportPath.isEmpty()) return 2;

    QString error;
    QMatrix4x4 calibration;
    QHash<int, PoseRecord> poses;
    if (!readCalibration(calibrationPath, &calibration, &error) || !readPoseInfo(posePath, &poses, &error)) return 2;
    pointcloud::IcpOptions options;
    options.enabled = !parser.isSet(transformOnlyOption);
    options.voxelLevels = parseLevels(parser.value(voxelOption), &error);
    options.correspondenceDistances = parseLevels(parser.value(distanceOption), &error);
    if (!error.isEmpty()) return 2;

    QDir directory(inputDirectory);
    const QStringList files = directory.entryList({QStringLiteral("*.ply")}, QDir::Files, QDir::Name);
    QVector<pointcloud::WorldCloudInput> inputs;
    QVector<PoseRecord> orderedPoses;
    const QRegularExpression scanPattern(QStringLiteral("A(\\d+)\\.ply$"), QRegularExpression::CaseInsensitiveOption);
    for (const QString &file : files) {
        const auto match = scanPattern.match(file);
        if (!match.hasMatch()) continue;
        const int scan = match.captured(1).toInt();
        if (!poses.contains(scan)) continue;
        const PoseRecord record = poses.value(scan);
        pointcloud::WorldCloudInput input;
        input.filePath = directory.absoluteFilePath(file);
        input.startBaseFromFlange = poseMatrix(record.start);
        input.endBaseFromFlange = poseMatrix(record.end);
        input.flangeFromDepth = calibration;
        inputs.push_back(input);
        orderedPoses.push_back(record);
    }

    pointcloud::WorldCloudMergeResult result;
    if (inputs.size() >= 2) result = pointcloud::mergePlyCloudsInWorld(inputs, options);
    else if (!options.enabled && inputs.size() == 1) result = pointcloud::mergePlyCloudsInWorld(inputs, options);
    else result.error = QStringLiteral("PLY 文件与位姿记录匹配后少于所需帧数");
    bool allAccepted = result.ok && result.icpDiagnostics.size() == inputs.size();
    if (options.enabled)
        for (int index = 1; index < result.icpDiagnostics.size(); ++index)
            allAccepted = allAccepted && result.icpDiagnostics[index].accepted;

    QJsonObject root;
    root.insert(QStringLiteral("schema"), QStringLiteral("pointcloudstitch-regression-v1"));
    root.insert(QStringLiteral("generated_at"), QDateTime::currentDateTime().toString(Qt::ISODateWithMs));
    root.insert(QStringLiteral("success"), allAccepted);
    root.insert(QStringLiteral("processing_mode"), options.enabled
        ?QStringLiteral("registration_only")
        :QStringLiteral("hand_eye_transform_only"));
    root.insert(QStringLiteral("registration_applied"), options.enabled&&allAccepted);
    root.insert(QStringLiteral("seam_fusion_applied"), false);
    root.insert(QStringLiteral("formal_output"), false);
    root.insert(QStringLiteral("error"), result.error);
    root.insert(QStringLiteral("diagnostics"), result.diagnostics);
    root.insert(QStringLiteral("input_directory"), QDir::toNativeSeparators(directory.absolutePath()));
    root.insert(QStringLiteral("pose_info"), QDir::toNativeSeparators(QFileInfo(posePath).absoluteFilePath()));
    root.insert(QStringLiteral("calibration"), QDir::toNativeSeparators(QFileInfo(calibrationPath).absoluteFilePath()));
    if (!outputDirectory.isEmpty()) root.insert(QStringLiteral("output_directory"), QDir::toNativeSeparators(QFileInfo(outputDirectory).absoluteFilePath()));
    QJsonArray inputArray;
    for (int index = 0; index < inputs.size(); ++index) {
        QJsonObject input;
        input.insert(QStringLiteral("scan"), orderedPoses[index].scan);
        input.insert(QStringLiteral("file"), inputs[index].filePath);
        input.insert(QStringLiteral("start"), vectorJson(orderedPoses[index].start));
        input.insert(QStringLiteral("end"), vectorJson(orderedPoses[index].end));
        inputArray.append(input);
    }
    root.insert(QStringLiteral("inputs"), inputArray);
    QJsonObject parameterObject;
    QJsonArray voxels, distances;
    for (float value : options.voxelLevels) voxels.append(value);
    for (float value : options.correspondenceDistances) distances.append(value);
    parameterObject.insert(QStringLiteral("voxel_levels_mm"), voxels);
    parameterObject.insert(QStringLiteral("correspondence_distances_mm"), distances);
    parameterObject.insert(QStringLiteral("icp_enabled"), options.enabled);
    parameterObject.insert(QStringLiteral("structural_validation_enabled"), options.structuralValidationEnabled);
    parameterObject.insert(QStringLiteral("structural_plane_exclusion_mm"), options.structuralPlaneExclusionMm);
    parameterObject.insert(QStringLiteral("minimum_degenerate_structural_coverage_3mm"), options.minimumDegenerateStructuralCoverage3mm);
    parameterObject.insert(QStringLiteral("minimum_structural_points"), options.minimumStructuralPoints);
    parameterObject.insert(QStringLiteral("structural_icp_enabled"), options.structuralIcpEnabled);
    parameterObject.insert(QStringLiteral("support_plane_sample_stride"), options.supportPlaneSampleStride);
    parameterObject.insert(QStringLiteral("tangent_coarse_alignment_enabled"), options.tangentCoarseAlignmentEnabled);
    parameterObject.insert(QStringLiteral("tangent_coarse_search_radius_mm"), options.tangentCoarseSearchRadiusMm);
    parameterObject.insert(QStringLiteral("tangent_coarse_step_mm"), options.tangentCoarseStepMm);
    parameterObject.insert(QStringLiteral("tangent_coarse_refine_step_mm"), options.tangentCoarseRefineStepMm);
    parameterObject.insert(QStringLiteral("tangent_coarse_minimum_coverage_gain"), options.tangentCoarseMinimumCoverageGain);
    parameterObject.insert(QStringLiteral("sample_stride"), options.sampleStride);
    parameterObject.insert(QStringLiteral("overlap_margin_mm"), options.overlapMargin);
    parameterObject.insert(QStringLiteral("plane_prealignment_enabled"), options.planePrealignmentEnabled);
    parameterObject.insert(QStringLiteral("maximum_plane_prealignment_translation_mm"), options.maximumPlanePrealignmentTranslation);
    parameterObject.insert(QStringLiteral("maximum_plane_prealignment_angle_deg"), options.maximumPlanePrealignmentAngleDegrees);
    parameterObject.insert(QStringLiteral("plane_identity_tracking_enabled"), options.planeIdentityTrackingEnabled);
    parameterObject.insert(QStringLiteral("plane_identity_height_tolerance_mm"), options.planeIdentityHeightToleranceMm);
    parameterObject.insert(QStringLiteral("plane_fit_height_band_mm"), options.planeFitHeightBandMm);
    parameterObject.insert(QStringLiteral("plane_fit_inlier_distance_mm"), options.planeFitInlierDistanceMm);
    parameterObject.insert(QStringLiteral("plane_fit_iterations"), options.planeFitIterations);
    parameterObject.insert(QStringLiteral("plane_identity_tracking_valid"), result.planeIdentityTrackingValid);
    parameterObject.insert(QStringLiteral("plane_identity_consensus_height_mm"), result.planeIdentityConsensusHeight);
    parameterObject.insert(QStringLiteral("plane_identity_diagnostics"), result.planeIdentityDiagnostics);
    QJsonArray trackedPlaneHeights;
    for(float height:result.trackedPlaneHeights)trackedPlaneHeights.append(height);
    parameterObject.insert(QStringLiteral("tracked_plane_heights_mm"),trackedPlaneHeights);
    parameterObject.insert(QStringLiteral("maximum_correction_translation_mm"), options.maximumCorrectionTranslation);
    parameterObject.insert(QStringLiteral("maximum_correction_angle_deg"), options.maximumCorrectionAngleDegrees);
    root.insert(QStringLiteral("parameters"), parameterObject);
    QJsonArray pairs;
    for (int index = 1; index < result.icpDiagnostics.size(); ++index)
        pairs.append(diagnosticJson(result.icpDiagnostics[index], options));
    root.insert(QStringLiteral("adjacent_pairs"), pairs);

    if (!outputDirectory.isEmpty()) {
        QDir output(outputDirectory);
        if (!output.exists() && !QDir().mkpath(outputDirectory)) return 3;
        QString outputError;
        QJsonArray preFiles,postFiles;
        if(options.enabled){
            for(int index=0;index<result.diagnosticPreIcpFrames.size();++index){
                const QString prePath=output.filePath(QStringLiteral("diagnostic_pre_icp_frame_%1.ply").arg(index+1,2,10,QChar('0')));
                const QString postPath=output.filePath(QStringLiteral("diagnostic_post_icp_frame_%1.ply").arg(index+1,2,10,QChar('0')));
                if(!writeAsciiPly(prePath,result.diagnosticPreIcpFrames[index],&outputError)
                    ||!writeAsciiPly(postPath,result.diagnosticPostIcpFrames.value(index),&outputError))return 3;
                preFiles.append(QDir::toNativeSeparators(prePath));postFiles.append(QDir::toNativeSeparators(postPath));
            }
        }
        root.insert(QStringLiteral("diagnostic_pre_icp_frame_files"),preFiles);
        root.insert(QStringLiteral("diagnostic_post_icp_frame_files"),postFiles);
        if(allAccepted&&!result.points.isEmpty()){
            const QString mergedPath = output.filePath(options.enabled
                ? QStringLiteral("regression_registered_robot_base.ply")
                : QStringLiteral("transformed_robot_base.ply"));
            if (!writeAsciiPly(mergedPath, result.points, &outputError)) return 3;
            QVector<pointcloud::Point3D> preview;
            preview.reserve((result.points.size() + 15) / 16);
            for (int index = 0; index < result.points.size(); index += 16)preview.push_back(result.points.at(index));
            const QString previewPath = output.filePath(options.enabled
                ? QStringLiteral("regression_registered_robot_base_preview.ply")
                : QStringLiteral("transformed_robot_base_preview.ply"));
            if (!writeAsciiPly(previewPath, preview, &outputError)) return 3;
            root.insert(QStringLiteral("diagnostic_registered_output"), QDir::toNativeSeparators(mergedPath));
            root.insert(QStringLiteral("diagnostic_registered_preview"), QDir::toNativeSeparators(previewPath));
        }
    }

    QDir().mkpath(QFileInfo(reportPath).absolutePath());
    QSaveFile report(reportPath);
    if (!report.open(QIODevice::WriteOnly)
        || report.write(QJsonDocument(root).toJson(QJsonDocument::Indented)) < 0
        || !report.commit()) return 3;
    return allAccepted ? 0 : 1;
}
