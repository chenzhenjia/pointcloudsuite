bool writeBinaryPlyFile(const QString &path, const QVector<pointcloud::Point3D> &points,
                   QString *error)
{
    pcv::detail::io::BinaryPlyWriteOptions options;
    options.includeNormals = true;
    options.comment = QStringLiteral("generated by pointcloudstitch");
    return pcv::detail::io::writeBinaryPly(path, points, error, options);
}

bool writePointMapping(const QString &path, const pointcloud::WorldCloudMergeResult &merge,
                       QString *error)
{
    if (merge.points.size() != merge.cloudIds.size()
        || merge.points.size() != merge.sourceIndices.size()
        || merge.points.size() != merge.scanRatios.size()) {
        if (error) *error = QObject::tr("点云来源映射长度不一致");
        return false;
    }
    QSaveFile file(path);
    if (!file.open(QIODevice::WriteOnly)) {
        if (error) *error = QObject::tr("无法创建点云来源映射：%1").arg(path);
        return false;
    }
    QDataStream stream(&file);
    stream.setByteOrder(QDataStream::LittleEndian);
    stream.setFloatingPointPrecision(QDataStream::SinglePrecision);
    stream << quint32(0x314D4350) << quint32(1) << quint64(merge.points.size());
    for (qsizetype i = 0; i < merge.points.size(); ++i)
        stream << qint32(merge.cloudIds[i]) << qint64(merge.sourceIndices[i])
               << merge.scanRatios[i];
    if (stream.status() != QDataStream::Ok || !file.commit()) {
        if (error) *error = QObject::tr("写入点云来源映射失败：%1").arg(path);
        return false;
    }
    return true;
}

QVector<pointcloud::Point3D> deterministicPreview(const QVector<pointcloud::Point3D> &points,
                                                   double keepRatio)
{
    keepRatio = qBound(0.01, keepRatio, 1.0);
    if (keepRatio >= 0.999) return points;
    const quint64 threshold = quint64(keepRatio
        * static_cast<long double>(std::numeric_limits<quint64>::max()));
    QVector<pointcloud::Point3D> preview;
    preview.reserve(qsizetype(double(points.size()) * keepRatio) + 1);
    for (const pointcloud::Point3D &point : points) {
        const qint64 x = qint64(std::floor(double(point.x) / 0.2));
        const qint64 y = qint64(std::floor(double(point.y) / 0.2));
        const qint64 z = qint64(std::floor(double(point.z) / 0.2));
        quint64 value = quint64(x) * 73856093ULL
            ^ quint64(y) * 19349663ULL
            ^ quint64(z) * 83492791ULL;
        value ^= value >> 30;
        value *= 0xBF58476D1CE4E5B9ULL;
        value ^= value >> 27;
        value *= 0x94D049BB133111EBULL;
        value ^= value >> 31;
        if (value <= threshold) preview.push_back(point);
    }
    return preview;
}

QString registrationPairStatus(const pointcloud::IcpDiagnostics &diagnostic)
{
    // 2.5D height-map status first: the operator must be able to tell the new
    // acceptance口径 apart from the legacy structural acceptance.
    if (diagnostic.visibilityHardRejected)
        return QObject::tr("低可见性拒绝");
    if (diagnostic.selectedRegistrationSource == QStringLiteral("heightmap_restricted_icp"))
        return QObject::tr("2.5D配准通过");
    if (diagnostic.heightMapRestrictedIcpDegenerate)
        return QObject::tr("受限ICP退化");
    if (diagnostic.heightMapRejectReason == QStringLiteral("heightmap_candidate_ambiguous"))
        return QObject::tr("2.5D候选歧义");
    if (diagnostic.heightMapFallbackToIcp)
        return QObject::tr("2.5D失败，回退旧ICP");
    if (diagnostic.accepted)
        return diagnostic.steepPlaneDetected
            ? QObject::tr("陡峭平面恢复通过") : QObject::tr("严格通过");
    if (diagnostic.reason == QStringLiteral("plane_tilt_exceeds_limit"))
        return QObject::tr("平面拟合不足：倾角超过 75 deg");
    if (diagnostic.reason.contains(QStringLiteral("steep_plane_feature_insufficient")))
        return QObject::tr("结构特征不足");
    if (diagnostic.overlapCoordinateSystem == QStringLiteral("plane_uvn")
        && (diagnostic.localOverlapSourcePoints < 100
            || diagnostic.localOverlapTargetPoints < 100))
        return QObject::tr("局部重叠不足");
    if (diagnostic.planePrealignmentAttempted && !diagnostic.planePrealignmentAccepted)
        return QObject::tr("坐标链风险或平面预对齐超限");
    return QObject::tr("配准未通过");
}

QString registrationFailureSummary(const QVector<pointcloud::IcpDiagnostics> &diagnostics)
{
    QStringList lines;
    for (int index = 1; index < diagnostics.size(); ++index) {
        const pointcloud::IcpDiagnostics &diagnostic = diagnostics[index];
        if (!diagnostic.accepted)
            lines.push_back(QObject::tr("scan %1：%2 (%3)")
                .arg(index + 1).arg(registrationPairStatus(diagnostic)).arg(diagnostic.reason));
    }
    return lines.join(QLatin1Char('\n'));
}

