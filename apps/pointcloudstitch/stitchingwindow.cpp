StitchTaskResult runStitching(const QVector<pointcloud::WorldCloudInput> &inputs,
                              const pointcloud::IcpOptions &icp,
                              const SeamFusionOptions &seamOptions,
                              const QString &outputDirectory,
                              const QString &calibrationPath,
                              double previewRatio,
                              bool writeSources,
                              bool diagnosticOutput,
                              const std::shared_ptr<std::atomic_bool> &cancelRequested,
                              const std::function<void(int, const QString &)> &progress)
{
    const auto reportProgress = [&progress](int value, const QString &message) {
        if (progress) progress(qBound(0, value, 100), message);
    };
    StitchTaskResult result;
    result.outputDirectory = outputDirectory;
    result.icpOptions = icp;
    result.transformOnly = !icp.enabled;
    pointcloud::IcpOptions runtimeIcp = icp;
    runtimeIcp.cancellation = cancelRequested;
    runtimeIcp.isCancelled = [cancelRequested]() {
        return cancelRequested && cancelRequested->load();
    };
    pcv::interface::StitchingRequest request;
    request.input.calibrationPath = calibrationPath;
    request.registration.options = runtimeIcp;
    request.registration.options.enabled = icp.enabled;
    request.registration.sampleStride = icp.sampleStride;
    request.registration.parallelEnabled = icp.parallelEnabled;
    request.registration.maxParallelTasks = icp.maxParallelTasks;
    request.registration.collectDiagnosticFrames = icp.collectDiagnosticFrames;
    request.registration.structuralCoverageOfMatched = icp.structuralCoverageOfMatched;
    request.registration.minimumStructuralMatchedRatio = icp.minimumStructuralMatchedRatio;
    request.registration.visibilityWarningRatio = icp.visibilityWarningRatio;
    request.registration.tangentCoarseTrimmedScore = icp.tangentCoarseTrimmedScore;
    request.registration.correspondenceParallelTasks = icp.correspondenceParallelTasks;
    request.registration.options.cancellation = cancelRequested;
    request.registration.options.isCancelled = [cancelRequested]() {
        return cancelRequested && cancelRequested->load();
    };
    request.seam.enabled = seamOptions.enabled;
    request.seam.halfWidthMm = seamOptions.halfWidth;
    request.artifacts.outputDirectory = outputDirectory;
    request.artifacts.allowOverwrite = true;
    request.artifacts.previewRatio = previewRatio;
    request.artifacts.writeSourceClouds = writeSources;
    request.artifacts.writeDiagnosticFrames = diagnosticOutput;
    request.isCancelled = [cancelRequested]() {
        return cancelRequested && cancelRequested->load();
    };
    request.progress = [&reportProgress](float value, const QString &message) {
        reportProgress(qRound(value * 78.0f), message);
    };
    for (const pointcloud::WorldCloudInput &input : inputs) {
        pcv::interface::StitchingFrameInput frame;
        frame.plyPath = input.filePath;
        frame.startPose = pointcloud::matrixToRobotPose(input.startBaseFromFlange);
        frame.endPose = pointcloud::matrixToRobotPose(input.endBaseFromFlange);
        request.input.frames.push_back(frame);
    }
    const pcv::interface::StitchingResult shared = pcv::interface::stitch(request);
    result.merge = shared.merge;
    result.merge.points = shared.points;
    result.merge.icpDiagnostics = shared.icpDiagnostics;
    result.merge.diagnostics = shared.diagnostics;
    result.seamFusion = shared.seamFusion;
    if (!shared.success) {
        if (shared.cancelled) {
            result.cancelled = true;
            return result;
        }
        result.error = shared.message.isEmpty()
            ? (result.transformOnly ? QObject::tr("点云手眼坐标转换失败")
                                    : QObject::tr("点云世界坐标转换或配准失败"))
            : shared.message;
        return result;
    }
    result.registrationAccepted = true;
    result.multiFrameConsistent = true;
    if (icp.enabled) {
        for (int index = 1; index < result.merge.icpDiagnostics.size(); ++index) {
            const auto&diagnostic=result.merge.icpDiagnostics[index];
            if (!diagnostic.accepted) {
                result.registrationAccepted = false;
            }
        }
    }
    result.multiFrameConsistent = result.registrationAccepted;
    if(icp.enabled){
        for(int index=1;index<result.merge.icpDiagnostics.size();++index)
            result.registrationApplied=result.registrationApplied||result.merge.icpDiagnostics[index].accepted;
    }
    result.mergedFile = shared.manifest.formalPly.isEmpty() ? shared.outputPly : shared.manifest.formalPly;
    result.previewFile = shared.manifest.previewPly;
    result.mappingFile = shared.manifest.mappingFile;
    result.reportFile = shared.manifest.reportJson;
    result.formalOutput = true;
    result.ok = true;
    result.seamFusionApplied = !shared.seamDiagnostics.isEmpty();
    result.previewCount = 0;
    result.merge.diagnostics += QStringLiteral("production_pipeline=pcv::interface::stitch\n");
    // v0.4 production boundary: module 30 has already committed the formal
    // PLY, preview, mapping and manifest through module 10's transaction.
    // The legacy application writer below remains only as a recorded rollback
    // point for the compatibility-cleanup batch and is unreachable in v0.4.
    return result;
    QDir directory(outputDirectory);
    reportProgress(79, QObject::tr("正在准备输出目录"));
    if (!directory.exists() && !QDir().mkpath(outputDirectory)) {
        result.error = QObject::tr("无法创建输出目录：%1").arg(outputDirectory);
        return result;
    }
    if(!result.transformOnly&&!result.registrationAccepted){
        QFile::remove(directory.filePath(QStringLiteral("stitched_robot_base.ply")));
        QFile::remove(directory.filePath(QStringLiteral("stitched_robot_base_preview.ply")));
        QFile::remove(directory.filePath(QStringLiteral("stitched_robot_base.pcvmap")));
    }
    if(!result.transformOnly&&diagnosticOutput){
        for(int index=0;index<result.merge.diagnosticPreIcpFrames.size();++index){
            const QString prePath=directory.filePath(QStringLiteral("diagnostic_pre_icp_frame_%1.ply").arg(index+1,2,10,QChar('0')));
            const QString postPath=directory.filePath(QStringLiteral("diagnostic_post_icp_frame_%1.ply").arg(index+1,2,10,QChar('0')));
            if(!writeBinaryPlyFile(prePath,result.merge.diagnosticPreIcpFrames[index],&result.error)
                ||!writeBinaryPlyFile(postPath,result.merge.diagnosticPostIcpFrames.value(index),&result.error))return result;
            result.diagnosticPreIcpFiles.push_back(prePath);
            result.diagnosticPostIcpFiles.push_back(postPath);
        }
    }
    if (writeSources) {
        // Single pass over the merged cloud: bucket each point under its own
        // cloud id instead of rescanning the whole merge per source frame.
        bool correctionsInvertible = true;
        QVector<QMatrix4x4> inverseCorrections(inputs.size());
        for (int cloudId = 0; cloudId < inputs.size() && correctionsInvertible; ++cloudId) {
            bool ok = false;
            inverseCorrections[cloudId] = result.merge.registrationCorrections
                .value(cloudId, QMatrix4x4()).inverted(&ok);
            if (!ok) {
                result.error = QObject::tr("第 %1 帧坐标修正矩阵不可逆").arg(cloudId + 1);
                return result;
            }
        }
        QVector<QVector<pointcloud::Point3D>> sourceBuckets(inputs.size());
        qsizetype bucketBudget = 0;
        for (const int id : result.merge.cloudIds)
            if (id >= 0 && id < sourceBuckets.size()) ++bucketBudget;
        for (QVector<pointcloud::Point3D> &bucket : sourceBuckets)
            bucket.reserve(qMax<qsizetype>(1, bucketBudget / qMax(1, sourceBuckets.size())));
        for (qsizetype index = 0; index < result.merge.points.size(); ++index) {
            const int cloudId = result.merge.cloudIds.value(index, -1);
            if (cloudId < 0 || cloudId >= sourceBuckets.size()) continue;
            pointcloud::Point3D point = result.merge.points[index];
            const QVector3D base = inverseCorrections[cloudId].map(
                QVector3D(point.x, point.y, point.z));
            point.x = base.x(); point.y = base.y(); point.z = base.z();
            sourceBuckets[cloudId].push_back(point);
        }
        for (int cloudId = 0; cloudId < inputs.size(); ++cloudId) {
            const QString base = QFileInfo(inputs[cloudId].filePath).completeBaseName();
            const QString path = directory.filePath(QStringLiteral("%1_%2_robot_base.ply")
                                                        .arg(cloudId + 1).arg(base));
            reportProgress(79, QObject::tr("正在写入全分辨率来源点云 %1/%2")
                .arg(cloudId + 1).arg(inputs.size()));
            if (!writeBinaryPlyFile(path, sourceBuckets[cloudId], &result.error)) return result;
            result.retainedSourceFiles.push_back(path);
        }
    }
    reportProgress(79, result.transformOnly
        ? QObject::tr("仅坐标转换模式，跳过配准与接缝融合")
        : (result.registrationAccepted
            ? QObject::tr("正在按真实重叠区执行接缝融合")
            : QObject::tr("配准失败，跳过正式接缝融合")));
    if (!result.transformOnly && result.registrationAccepted && !shared.seamFusion.ok) {
        QElapsedTimer seamClock;
        seamClock.start();
        result.seamFusion = applyTrajectorySeamFusion(&result.merge, inputs, seamOptions);
        result.seamFusionMs = seamClock.elapsed();
    }
    else if (!shared.seamFusion.ok) {
        result.seamFusion.inputPoints = result.merge.points.size();
        result.seamFusion.outputPoints = result.merge.points.size();
        result.seamFusion.ok = true;
    }
    if (!result.transformOnly && result.registrationAccepted
        && !result.seamFusion.ok) {
        result.error = result.seamFusion.error.isEmpty()
            ? QObject::tr("接缝融合失败") : result.seamFusion.error;
        return result;
    }
    if (result.seamFusion.cancelled) {
        result.cancelled = true;
        return result;
    }
    for(const SeamFusionDiagnostic &diagnostic:result.seamFusion.diagnostics)
        result.seamFusionApplied=result.seamFusionApplied||diagnostic.applied;
    for (const SeamFusionDiagnostic &diagnostic : result.seamFusion.diagnostics) {
        result.merge.diagnostics += QStringLiteral(
            "Seam %1-%2: ranges=[%3,%4]/[%5,%6], overlap=[%7,%8], seam=%9, band=%10/%11, mutual=%12, interpolated=%13, unmatched preserved=%14, cells=%15, %16\n")
            .arg(diagnostic.cloudA + 1).arg(diagnostic.cloudB + 1)
            .arg(diagnostic.projectedAMin).arg(diagnostic.projectedAMax)
            .arg(diagnostic.projectedBMin).arg(diagnostic.projectedBMax)
            .arg(diagnostic.actualOverlapMin).arg(diagnostic.actualOverlapMax)
            .arg(diagnostic.seamProjection).arg(diagnostic.bandPointsA).arg(diagnostic.bandPointsB)
            .arg(diagnostic.mutualPairs).arg(diagnostic.interpolatedPoints)
            .arg(diagnostic.unmatchedPreserved).arg(diagnostic.decisionCells).arg(diagnostic.reason);
    }
    if (cancelRequested && cancelRequested->load()) {
        result.cancelled = true;
        return result;
    }

    result.pointsBeforeOutputDownsample=result.merge.points.size();
    result.outputDownsampleVoxelSize=0.0f;
    result.merge.diagnostics+=QStringLiteral(
        "Output downsample disabled for formal result: points=%1, all real points retained\n")
        .arg(result.merge.points.size());

    reportProgress(85, QObject::tr("正在准备输出目录"));
    QElapsedTimer outputClock;
    outputClock.start();
    result.mergedFile = directory.filePath(result.transformOnly
        ? QStringLiteral("transformed_robot_base.ply")
        : (result.registrationAccepted
            ? QStringLiteral("stitched_robot_base.ply")
            : QStringLiteral("diagnostic_unregistered_robot_base.ply")));
    reportProgress(87, result.transformOnly
        ? QObject::tr("正在写入手眼转换后的机器人基坐标点云")
        : (result.registrationAccepted
            ? QObject::tr("正在写入机器人基坐标合并点云")
            : QObject::tr("配准未全部通过，正在写入诊断点云")));
    if (!writeBinaryPlyFile(result.mergedFile, result.merge.points, &result.error)) {
        result.outputMs = outputClock.elapsed();
        return result;
    }

    result.mappingFile = result.mergedFile;
    result.mappingFile.replace(QRegularExpression(QStringLiteral("\\.ply$")),
                               QStringLiteral(".pcvmap"));
    if (!writePointMapping(result.mappingFile, result.merge, &result.error)) {
        result.outputMs = outputClock.elapsed();
        return result;
    }

    if (cancelRequested && cancelRequested->load()) {
        result.cancelled = true;
        return result;
    }
    const QVector<pointcloud::Point3D> preview = deterministicPreview(result.merge.points, previewRatio);
    result.previewCount = preview.size();
    result.previewFile = directory.filePath(result.transformOnly
        ? QStringLiteral("transformed_robot_base_preview.ply")
        : (result.registrationAccepted
            ?QStringLiteral("stitched_robot_base_preview.ply")
            :QStringLiteral("diagnostic_unregistered_robot_base_preview.ply")));
    reportProgress(92, QObject::tr("正在写入预览点云"));
    if (!writeBinaryPlyFile(result.previewFile, preview, &result.error)) {
        result.outputMs = outputClock.elapsed();
        return result;
    }

    result.reportFile = directory.filePath(result.transformOnly
        ? QStringLiteral("coordinate_transform_report.json")
        : QStringLiteral("stitching_report.json"));
    result.formalOutput=result.transformOnly||result.registrationAccepted;
    result.ok = result.formalOutput;
    reportProgress(99, result.transformOnly
        ? QObject::tr("正在写入坐标转换报告")
        : QObject::tr("正在写入配准报告"));
    if (!writeReport(result.reportFile, result, &result.error)) result.ok = false;
    result.outputMs = outputClock.elapsed();
    if (result.transformOnly && result.ok) {
        reportProgress(100, QObject::tr("手眼坐标转换和全部输出完成"));
    } else if (result.registrationAccepted && result.ok) {
        reportProgress(100, QObject::tr("点云配准和全部输出完成"));
    } else if (!result.registrationAccepted) {
        result.error = QObject::tr("至少一组相邻点云未通过参考 ICP 流程；未生成正式合并文件。\n%1\n诊断点云：%2\n报告：%3")
            .arg(registrationFailureSummary(result.merge.icpDiagnostics), result.mergedFile, result.reportFile);
        reportProgress(100, QObject::tr("配准失败，诊断文件已生成"));
    }
    return result;
}

QString numericText(double value)
{
    return QString::number(value, 'g', 12);
}

QString poseText(const QVector<double> &pose)
{
    QStringList values;
    values.reserve(pose.size());
    for (double value : pose) values.push_back(numericText(value));
    return values.join(QLatin1Char(' '));
}

bool parsePoseText(const QString &text, QVector<double> *pose)
{
    if (!pose) return false;
    pose->clear();
    const QStringList parts = text.trimmed().split(
        QRegularExpression(QStringLiteral("[\\s,，]+")), Qt::SkipEmptyParts);
    if (parts.size() != 6) return false;
    pose->reserve(6);
    for (const QString &part : parts) {
        bool ok = false;
        const double value = part.toDouble(&ok);
        if (!ok || !std::isfinite(value)) {
            pose->clear();
            return false;
        }
        pose->push_back(value);
    }
    return true;
}

